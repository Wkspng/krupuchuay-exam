async function findCategoryId() {
  const snap = await db.collection('categories').get();
  let id = null;
  snap.forEach(doc => { if (String(doc.data().name || '').trim() === CATEGORY_NAME) id = doc.id; });
  if (!id) throw new Error(`ไม่พบ category "${CATEGORY_NAME}"`);
  return id;
}

