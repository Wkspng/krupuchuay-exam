async function resolveCategoryIds() {
  const snap = await db.collection('categories').get();
  const map = new Map();
  snap.forEach(doc => map.set(String(doc.data().name || '').trim(), doc.id));
  return map;
}

async function main() {
  const dryRun = process.argv.includes('--dry-run');
  console.log(`โหมด: ${dryRun ? 'DRY-RUN' : 'APPLY'} | เตรียม ${QUESTIONS.length} ข้อ`);
  QUESTIONS.forEach((q, i) => {
    if (!q.q || !q.q.trim()) throw new Error(`ข้อ ${i}: ไม่มีโจทย์`);
    if (!Array.isArray(q.opts) || q.opts.length !== 4) throw new Error(`ข้อ ${i}: ต้องมี 4 ตัวเลือก`);
    if (q.opts.some(o => !String(o).trim())) throw new Error(`ข้อ ${i}: ตัวเลือกว่าง`);
    if (!Number.isInteger(q.ans) || q.ans < 0 || q.ans > 3) throw new Error(`ข้อ ${i}: ans ต้อง 0-3`);
  });
  const catIds = await resolveCategoryIds();
  const usedCats = [...new Set(QUESTIONS.map(q => q.cat))];
  usedCats.forEach(c => { if (!catIds.get(c)) throw new Error(`ไม่พบ category "${c}"`); console.log(`✅ ${c} (${catIds.get(c)})`); });

  const existingByCat = {};
  for (const c of usedCats) {
    const snap = await db.collection('questions').where('categoryId', '==', catIds.get(c)).get();
    const set = new Set(); snap.forEach(d => set.add(String(d.data().questionText || '').trim().toLowerCase()));
    existingByCat[c] = set;
  }

  const perCat = {};
  let imported = 0, skipped = 0, batch = db.batch(), ops = 0;
  for (const q of QUESTIONS) {
    const text = q.q.trim();
    if (existingByCat[q.cat].has(text.toLowerCase())) { skipped++; continue; }
    perCat[q.cat] = (perCat[q.cat] || 0) + 1;
    if (!dryRun) {
      const ref = db.collection('questions').doc();
      batch.set(ref, {
        categoryId: catIds.get(q.cat), categoryName: q.cat, questionText: text,
        choices: q.opts.map(o => String(o).trim()), correctAnswerIndex: q.ans,
        explanation: String(q.explain || '').trim(), difficulty: q.diff || 'medium',
        source: `ครูผู้ช่วย — ${q.src}`, topic: q.src,
        isActive: true, createdAt: new Date(), updatedAt: new Date(), legacyMongoId: null,
      });
      if (++ops >= 400) { await batch.commit(); batch = db.batch(); ops = 0; }
    }
    imported++;
  }
  if (!dryRun && ops > 0) await batch.commit();
  console.log(`\n✅ ${dryRun ? 'จะเพิ่ม' : 'เพิ่มแล้ว'} ${imported} ข้อ | ข้ามซ้ำ ${skipped}`);
  console.log('แยกตามหมวด:', JSON.stringify(perCat, null, 0));
  if (!dryRun) { console.log('\n⚠️  recompile หมวดเหล่านี้:'); usedCats.forEach(c => console.log(`   ${catIds.get(c)}  (${c})`)); }
  process.exit(0);
}
main().catch(e => { console.error('❌', e.message); process.exit(1); });
