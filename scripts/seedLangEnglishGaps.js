async function resolveCategoryIds() {
  const snap = await db.collection('categories').get();
  const map = new Map();
  snap.forEach(doc => map.set(String(doc.data().name || '').trim(), doc.id));
  return map;
}

async function main() {
  const dryRun = process.argv.includes('--dry-run');
  console.log(`โหมด: ${dryRun ? 'DRY-RUN (ไม่เขียนข้อมูล)' : 'APPLY (เขียนลง Firestore)'}`);
  console.log(`เตรียมข้อสอบ ${QUESTIONS.length} ข้อ`);

  QUESTIONS.forEach((q, i) => {
    if (!q.q || !q.q.trim()) throw new Error(`ข้อ ${i}: ไม่มีโจทย์`);
    if (!Array.isArray(q.opts) || q.opts.length !== 4) throw new Error(`ข้อ ${i}: ต้องมี 4 ตัวเลือก`);
    if (q.opts.some(o => !String(o).trim())) throw new Error(`ข้อ ${i}: มีตัวเลือกว่าง`);
    if (!Number.isInteger(q.ans) || q.ans < 0 || q.ans > 3) throw new Error(`ข้อ ${i}: ans ต้องเป็น 0-3`);
  });

  const catIds = await resolveCategoryIds();
  const usedCats = [...new Set(QUESTIONS.map(q => q.cat))];
  usedCats.forEach(c => {
    if (!catIds.get(c)) throw new Error(`ไม่พบ category "${c}"`);
    console.log(`✅ category: ${c} (${catIds.get(c)})`);
  });

  // โหลดข้อสอบเดิมของทุก category ที่ใช้ เพื่อกันซ้ำ
  const existingByCat = {};
  for (const c of usedCats) {
    const id = catIds.get(c);
    const snap = await db.collection('questions').where('categoryId', '==', id).get();
    const set = new Set();
    snap.forEach(doc => set.add(String(doc.data().questionText || '').trim().toLowerCase()));
    existingByCat[c] = set;
    console.log(`📦 ${c}: เดิม ${snap.size} ข้อ`);
  }

  let imported = 0, skipped = 0;
  let batch = db.batch();
  let ops = 0;

  for (const q of QUESTIONS) {
    const text = q.q.trim();
    if (existingByCat[q.cat].has(text.toLowerCase())) { skipped++; continue; }

    if (!dryRun) {
      const ref = db.collection('questions').doc();
      batch.set(ref, {
        categoryId: catIds.get(q.cat),
        categoryName: q.cat,
        questionText: text,
        choices: q.opts.map(o => String(o).trim()),
        correctAnswerIndex: q.ans,
        explanation: String(q.explain || '').trim(),
        difficulty: q.diff || 'medium',
        source: `${q.cat === EN ? 'ทักษะภาษาอังกฤษ' : 'คิดวิเคราะห์เชิงภาษา'} — ${q.src}`,
        topic: q.src,
        isActive: true,
        createdAt: new Date(),
        updatedAt: new Date(),
        legacyMongoId: null,
      });
      ops++;
      if (ops >= 400) { await batch.commit(); batch = db.batch(); ops = 0; }
    }
    imported++;
  }

  if (!dryRun && ops > 0) await batch.commit();

  console.log(`\n✅ เสร็จสิ้น: ${dryRun ? 'จะเพิ่ม' : 'เพิ่มแล้ว'} ${imported} ข้อ | ข้ามซ้ำ ${skipped} ข้อ`);
  if (!dryRun) {
    console.log('\n⚠️  อย่าลืม recompile exam pack ทั้ง 2 หมวด (จะรีเฟรชจำนวนข้อให้ด้วย):');
    usedCats.forEach(c => console.log(`   node scripts/compileExamPacks.js --apply --categoryId ${catIds.get(c)}`));
  }
  process.exit(0);
}

main().catch(err => { console.error('❌ ล้มเหลว:', err.message); process.exit(1); });
