async function findCategoryId() {
  const snap = await db.collection('categories').get();
  let id = null;
  snap.forEach(doc => {
    if (String(doc.data().name || '').trim() === CATEGORY_NAME) id = doc.id;
  });
  if (!id) throw new Error(`ไม่พบ category "${CATEGORY_NAME}"`);
  return id;
}

async function main() {
  const dryRun = process.argv.includes('--dry-run');
  console.log(`โหมด: ${dryRun ? 'DRY-RUN (ไม่เขียนข้อมูล)' : 'APPLY (เขียนลง Firestore)'}`);
  console.log(`เตรียมข้อสอบ ${QUESTIONS.length} ข้อ`);

  // ตรวจความถูกต้องเบื้องต้น
  QUESTIONS.forEach((q, i) => {
    if (!q.q || !q.q.trim()) throw new Error(`ข้อ ${i}: ไม่มีโจทย์`);
    if (!Array.isArray(q.opts) || q.opts.length !== 4) throw new Error(`ข้อ ${i}: ต้องมี 4 ตัวเลือก`);
    if (!Number.isInteger(q.ans) || q.ans < 0 || q.ans > 3) throw new Error(`ข้อ ${i}: ans ต้องเป็น 0-3`);
  });

  const categoryId = await findCategoryId();
  console.log(`✅ category: ${CATEGORY_NAME} (${categoryId})`);

  // โหลดข้อสอบเดิมในหมวดนี้เพื่อกันซ้ำ
  const existingSnap = await db.collection('questions').where('categoryId', '==', categoryId).get();
  const existingTexts = new Set();
  existingSnap.forEach(doc => existingTexts.add(String(doc.data().questionText || '').trim().toLowerCase()));
  console.log(`📦 ข้อสอบเดิมในหมวด: ${existingSnap.size} ข้อ`);

  let imported = 0, skipped = 0;
  let batch = db.batch();
  let ops = 0;

  for (const q of QUESTIONS) {
    const text = q.q.trim();
    if (existingTexts.has(text.toLowerCase())) { skipped++; continue; }

    if (!dryRun) {
      const ref = db.collection('questions').doc();
      batch.set(ref, {
        categoryId,
        categoryName: CATEGORY_NAME,
        questionText: text,
        choices: q.opts.map(o => String(o).trim()),
        correctAnswerIndex: q.ans,
        explanation: String(q.explain || '').trim(),
        difficulty: q.diff || 'medium',
        source: `คิดวิเคราะห์เชิงปริมาณ — ${q.topic}`,
        topic: q.topic,
        isActive: true,
        createdAt: new Date(),
        updatedAt: new Date(),
        legacyMongoId: null,
      });
      ops++;
      if (ops >= 400) { await batch.commit(); batch = db.batch(); ops = 0; }
    }
    imported++;
  }

  if (!dryRun && ops > 0) await batch.commit();

  console.log(`\n✅ เสร็จสิ้น: ${dryRun ? 'จะเพิ่ม' : 'เพิ่มแล้ว'} ${imported} ข้อ | ข้ามซ้ำ ${skipped} ข้อ`);
  if (!dryRun) console.log(`\n⚠️  อย่าลืม recompile exam pack: node scripts/compileExamPacks.js --apply --categoryId ${categoryId}`);
  process.exit(0);
}

main().catch(err => { console.error('❌ ล้มเหลว:', err.message); process.exit(1); });
